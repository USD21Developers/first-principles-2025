import { createHash } from "node:crypto";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const artifactRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const fpRoot = path.join(artifactRoot, "public", "fp");
const allowedExtensions = new Set([
  ".avif", ".css", ".gif", ".html", ".ico", ".jpg", ".jpeg", ".js",
  ".json", ".md", ".png", ".svg", ".webp",
]);

function shouldInclude(relativePath) {
  const normalized = relativePath.split(path.sep).join("/");
  const basename = path.posix.basename(normalized);

  if (!allowedExtensions.has(path.extname(basename).toLowerCase())) return false;
  if (normalized.includes("/node_modules/") || normalized.startsWith("node_modules/")) return false;
  if (normalized.includes("/_assets/img/screenshots/")) return false;
  if (normalized.includes("/_assets/img/icons/launch/fp/")) return false;
  if (basename === "sw.js" || basename === "sw.js.map") return false;
  if (basename === "workbox-config.js" || basename.startsWith("workbox-")) return false;
  if (basename === "package.json" || basename === "package-lock.json") return false;
  if (basename === "ai.txt") return false;

  return true;
}

async function collectFiles(directory, relativeDirectory = "") {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const relativePath = path.join(relativeDirectory, entry.name);
    const absolutePath = path.join(directory, entry.name);

    if (entry.isDirectory()) {
      if (entry.name !== "node_modules") {
        files.push(...await collectFiles(absolutePath, relativePath));
      }
    } else if (entry.isFile() && shouldInclude(relativePath)) {
      files.push(relativePath.split(path.sep).join("/"));
    }
  }

  return files;
}

const files = (await collectFiles(fpRoot)).sort();
const manifest = [];
const buildHash = createHash("sha256");

for (const relativePath of files) {
  const contents = await readFile(path.join(fpRoot, relativePath));
  const revision = createHash("sha256").update(contents).digest("hex").slice(0, 16);
  manifest.push({ url: relativePath, revision });
  buildHash.update(relativePath).update("\0").update(revision).update("\0");
}

const buildId = buildHash.digest("hex").slice(0, 16);
const worker = `/* Generated by scripts/generate-fp-service-worker.mjs. */
"use strict";

const BUILD_ID = ${JSON.stringify(buildId)};
const PRECACHE_NAME = "fp-precache-" + BUILD_ID;
const RUNTIME_NAME = "fp-runtime-" + BUILD_ID;
const APP_CACHE_PREFIXES = ["fp-precache-", "fp-runtime-"];
const PRECACHE = ${JSON.stringify(manifest)};

self.addEventListener("install", (event) => {
  self.skipWaiting();
  event.waitUntil((async () => {
    const cache = await caches.open(PRECACHE_NAME);
    const batchSize = 24;
    for (let index = 0; index < PRECACHE.length; index += batchSize) {
      const batch = PRECACHE.slice(index, index + batchSize);
      await Promise.all(batch.map(async ({ url }) => {
        const request = new Request(new URL(url, self.registration.scope), {
          cache: "reload",
          credentials: "same-origin",
        });
        const response = await fetch(request);
        if (!response.ok) throw new Error("Unable to precache " + request.url);
        await cache.put(request, response);
      }));
    }
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.map((name) => {
      const isAppCache = APP_CACHE_PREFIXES.some((prefix) => name.startsWith(prefix));
      const isLegacyFpCache = name.startsWith("workbox-") && name.includes("/fp/");
      return (isAppCache && name !== PRECACHE_NAME && name !== RUNTIME_NAME) || isLegacyFpCache
        ? caches.delete(name)
        : Promise.resolve(false);
    }));
    await self.clients.claim();
  })());
});

function normalizedRequest(request) {
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return request;
  if (url.pathname.endsWith("/")) url.pathname += "index.html";
  if (request.mode === "navigate" || request.destination === "document") {
    url.search = "";
  } else {
    for (const key of [...url.searchParams.keys()]) {
      if (key.startsWith("utm_") || key === "fbclid") url.searchParams.delete(key);
    }
  }
  return new Request(url.href, { credentials: "same-origin" });
}

async function matchCurrentCaches(request) {
  const normalized = normalizedRequest(request);
  return (await caches.open(PRECACHE_NAME)).match(normalized)
    || (await caches.open(RUNTIME_NAME)).match(normalized);
}

async function networkFirst(request) {
  try {
    const response = await fetch(request, { cache: "no-cache" });
    if (response && response.ok) {
      const cache = await caches.open(RUNTIME_NAME);
      await cache.put(normalizedRequest(request), response.clone());
    }
    return response;
  } catch {
    return (await matchCurrentCaches(request))
      || (await caches.open(PRECACHE_NAME)).match(new URL("index.html", self.registration.scope));
  }
}

async function cacheFirst(request) {
  const cached = await matchCurrentCaches(request);
  if (cached) return cached;

  const response = await fetch(request);
  if (response.ok && request.url.startsWith(self.registration.scope)) {
    const cache = await caches.open(RUNTIME_NAME);
    await cache.put(normalizedRequest(request), response.clone());
  }
  return response;
}

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin || !url.href.startsWith(self.registration.scope)) return;

  const isHtml = event.request.mode === "navigate"
    || event.request.destination === "document"
    || url.pathname.endsWith(".html");
  event.respondWith(isHtml
    ? networkFirst(event.request)
    : cacheFirst(event.request));
});
`;

await writeFile(path.join(fpRoot, "sw.js"), worker);
const totalBytes = (await Promise.all(files.map((file) => stat(path.join(fpRoot, file)))))
  .reduce((total, fileStat) => total + fileStat.size, 0);
console.log(`Generated fp/sw.js build ${buildId}: ${files.length} files, ${Math.round(totalBytes / 1024 / 1024)} MiB.`);